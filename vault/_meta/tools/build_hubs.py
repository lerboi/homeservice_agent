"""Regenerate the hub note of each list-style folder from its notes' frontmatter.
Run from the repo root:  python vault/_meta/tools/build_hubs.py"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
V = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
HUBS = {
    "Log": ("Dated record of work: audits, fix waves, investigations. Newest first. Entries are true when written and are not maintained; `superseded` entries were replaced by a later one.", True),
    "Decisions": ("One decision per note: context, decision, consequences.", False),
    "Plans": ("Plans that are not finished. A finished plan moves to Log.", False),
    "Reference": ("Research, SDK gotchas, pointers to external resources, documents.", False),
    "Product": ("Positioning, site flow, backlog and ideas.", False),
    "Runbooks": ("Step-by-step operational procedures.", False),
}


def front(path):
    d = {}
    with open(path, encoding="utf-8") as f:
        if f.readline().strip() != "---":
            return d
        for line in f:
            if line.strip() == "---":
                break
            m = re.match(r"^(\w+):\s*(.*)$", line)
            if m:
                d[m.group(1)] = m.group(2).strip().strip('"').replace('\\"', '"')
    return d


for folder, (blurb, newest_first) in HUBS.items():
    d = os.path.join(V, folder)
    rows = []
    for f in sorted(os.listdir(d), reverse=newest_first):
        if not f.endswith(".md") or f == folder + ".md":
            continue
        fm = front(os.path.join(d, f))
        desc = fm.get("description", "").replace("|", "/")
        rows.append((f[:-3], fm.get("status", ""), desc))
    out = ["---", "type: hub", "status: current", f'description: "{blurb}"', "tags: [voco/hub]", "---", "",
           f"# {folder}", "", "Up: [[Home]]", "", blurb, "",
           "This table is generated by `vault/_meta/tools/build_hubs.py`. Edit the notes, not the table.", "",
           "| Note | Status | Description |", "|---|---|---|"]
    out += [f"| [[{n}]] | {s} | {desc} |" for n, s, desc in rows]
    open(os.path.join(d, folder + ".md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(folder, len(rows))
